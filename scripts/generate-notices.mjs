import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const lock = JSON.parse(readFileSync(resolve(root, 'package-lock.json'), 'utf8'));
const overrides = { 'react-remove-scroll-bar@2.3.8': 'licenses/react-remove-scroll-bar-2.3.8.LICENSE' };
const notices = new Map();
for (const [location, entry] of Object.entries(lock.packages)) {
  if (!location.startsWith('node_modules/') || entry.dev || entry.link) continue;
  const directory = resolve(root, location);
  const pkg = JSON.parse(readFileSync(resolve(directory, 'package.json'), 'utf8'));
  const key = `${pkg.name}@${pkg.version}`;
  if (notices.has(key)) continue;
  const files = readdirSync(directory).filter(name => /^(license|licence|copying|notice)(?:$|[.-])/i.test(name)).sort();
  const texts = overrides[key] ? [readFileSync(resolve(root, overrides[key]), 'utf8')]
    : files.map(name => readFileSync(resolve(directory, name), 'utf8'));
  if (!texts.length) throw new Error(`Missing license notice: ${key}`);
  notices.set(key, `${key} (${pkg.license ?? entry.license ?? 'See license below'})\n${texts.map(text => text.replace(/\r\n?/g, '\n').trim()).join('\n\n')}`);
}
const content = 'RadishUI — third-party runtime dependency notices\n\n' +
  'Generated by scripts/generate-notices.mjs from package-lock.json and installed package license files.\n' +
  'Includes installed production dependencies; a particular build may use only a subset.\n' +
  'The react-remove-scroll-bar notice omitted by its npm archive is retained in licenses/ with its upstream source.\n\n' +
  [...notices].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([, text]) => `${'-'.repeat(72)}\n${text}\n`).join('\n');
const output = resolve(root, 'apps/docs/public/third-party-notices.txt');
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== content) throw new Error('Third-party notices are outdated. Run npm run notices:generate.');
  console.log(`Third-party notices match (${notices.size} packages).`);
} else {
  mkdirSync(resolve(root, 'apps/docs/public'), { recursive: true });
  writeFileSync(output, content);
  console.log(`Generated third-party notices (${notices.size} packages).`);
}
